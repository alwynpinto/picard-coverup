PICARD_TYPES = {
    ArtType.FRONT: ["front"],
    ArtType.BACK: ["back"],
    ArtType.DISC: ["medium"],
    ArtType.BOOKLET: ["booklet"],
}

SCRIPT_VARIABLES = {
    "_coverup_status": "CoverUp result for the album: applied, review, none or skipped.",
    "_coverup_source": "Source of the applied front cover (caa, discogs, fanart, ... or generated).",
    "_coverup_confidence": "Tier of the applied front cover: A exact release, B release group, C other, G generated.",
    "_coverup_generated": "1 when the applied front cover was generated by CoverUp (AI or template).",
}


@dataclass
class State:
    api: object = None
    version: str = "0"
    log_handle: object = None
    pending: dict[str, FolderPlan] = field(default_factory=dict)  # album key -> files to write after save
    last_batch: dict[str, tuple[str, list[str]]] = field(default_factory=dict)  # album key -> (batch, folders)
    cancel: threading.Event = field(default_factory=threading.Event)

    def settings(self) -> Settings:
        cfg = getattr(self.api, "plugin_config", None)
        return Settings.from_mapping(cfg)

    def cache_root(self) -> Path:
        try:
            from picard.const import appdirs

            return Path(appdirs.cache_folder()) / "coverup"
        except Exception:
            return Path.home() / ".cache" / "coverup"

    def config_root(self) -> Path:
        try:
            from picard.const import appdirs

            return Path(appdirs.config_folder()) / "coverup"
        except Exception:
            return Path.home() / ".config" / "coverup"

    def user_templates_dir(self) -> Path:
        return self.config_root() / "templates"

    def http(self, cancel: threading.Event | None = None) -> HttpClient:
        s = self.settings()
        if self.log_handle is not None:
            self.log_handle.set_secrets(s.secrets())
        return HttpClient(
            version=self.version, cache_dir=self.cache_root() / "http", cache_hours=float(s["http_cache_hours"]),
            cancel=cancel or threading.Event(),
        )

    def pipeline(self, cancel: threading.Event | None = None) -> Pipeline:
        return Pipeline(self.settings(), self.http(cancel), imaging.fingerprint)


STATE = State()


# ---- picard object helpers ------------------------------------------------------------------------

def _classes():
    from picard.plugin3.api import Album, Cluster, File, Track

    return Album, Cluster, File, Track


def target_of(obj):
    """Album or Cluster that an action on ``obj`` should work on (or None)."""
    Album, Cluster, File, Track = _classes()
    if isinstance(obj, Album):
        return obj
    if isinstance(obj, Track):
        return getattr(obj, "album", None)
    if isinstance(obj, Cluster):
        return obj
    if isinstance(obj, File):
        parent = obj.parent_item
        if isinstance(parent, Track):
            return getattr(parent, "album", None)
        if isinstance(parent, Cluster):
            return parent
    return None


def unique_targets(objs) -> list:
    out, seen = [], set()
    for o in objs:
        t = target_of(o)
        if t is not None and id(t) not in seen:
            seen.add(id(t))
            out.append(t)
    return out


def key_of(target) -> str:
    Album, Cluster, _F, _T = _classes()
    if isinstance(target, Album):
        return f"album:{target.id}"
    return f"cluster:{id(target)}"


def iter_files(target):
    if hasattr(target, "iterfiles"):
        yield from target.iterfiles()
    else:
        yield from getattr(target, "files", [])


def _int(v, default=None):
    try:
        return int(str(v).split("/")[0])
    except (TypeError, ValueError):
        return default


def query_from(target) -> Query:
    md = target.metadata
    files = list(iter_files(target))
    dirs = []
    for f in files:
        d = os.path.dirname(f.filename)
        if d and d not in dirs:
            dirs.append(d)
    year = None
    for k in ("date", "originaldate"):
        if md.get(k):
            year = _int(md[k][:4])
            if year:
                break
    disc_numbers = {disc_for_track(f.metadata.get("discnumber")) for f in files} or {1}
    q = Query(
        artist=md.get("albumartist") or md.get("artist") or "",
        album=md.get("album") or "",
        year=year,
        barcode=md.get("barcode") or "",
        catalog_number=md.get("catalognumber") or "",
        label=md.get("label") or "",
        country=md.get("releasecountry") or "",
        format=md.get("media") or "",
        medium_count=max(_int(md.get("totaldiscs"), 1) or 1, max(disc_numbers)),
        release_mbid=md.get("musicbrainz_albumid") or "",
        rg_mbid=md.get("musicbrainz_releasegroupid") or "",
        artist_mbid=(md.getall("musicbrainz_albumartistid") or [""])[0] if hasattr(md, "getall") else md.get("musicbrainz_albumartistid", ""),
        genre=(md.get("genre") or "").split(";")[0].strip(),
        track_count=_int(md.get("~totalalbumtracks") or md.get("totaltracks"), 0) or len(getattr(target, "tracks", []) or files),
        album_dirs=dirs,
    )
    return q


def existing_front(target) -> Candidate | None:
    """The front image currently on the album (embedded/loaded), as a comparison reference."""
    try:
        img = target.orig_metadata.images.get_front_image() or target.metadata.images.get_front_image()
    except Exception:
        img = None
    if img is None:
        return None
    try:
        data = img.data
    except Exception:
        return None
    if not data:
        return None
    c = Candidate("embedded", "embedded-front", "", ArtType.FRONT, Tier.B, width=getattr(img, "width", 0) or 0,
                  height=getattr(img, "height", 0) or 0, dims_known=True, thumb_data=data, data=data, attribution="current cover")
    return c


# ---- applying -------------------------------------------------------------------------------------

def _make_image(data: bytes, art: ArtType, comment: str, url: str = ""):
    from picard.plugin3.api import CoverArtImage

    img = CoverArtImage(url=url or None, types=list(PICARD_TYPES[art]), comment=comment, data=data, support_types=True)
    img.is_front = art == ArtType.FRONT
    # CoverUp writes its own files (custom folder and names); keep Picard's file saving out of it
    img.can_be_saved_to_disk = False
    return img


def _strip_types(obj, types: set[str]) -> None:
    for attr in ("metadata",):
        md = getattr(obj, attr, None)
        if md is None:
            continue
        images = md.images
        for i in range(len(images) - 1, -1, -1):
            img_types = {t.lower() for t in (images[i].types or [])}
            if img_types & types or (("front" in types) and images[i].is_front_image()):
                del images[i]


def embed(target, items: list[PlanItem], s: Settings) -> list[str]:
    """Attach images to the album/cluster (and per-disc to that disc's files). Saved by Picard on save."""
    from picard.coverart.setters import CoverArtSetter, CoverArtSetterMode

    notes: list[str] = []
    embeddable = [it for it in items if it.art_type in PICARD_TYPES]
    if not embeddable:
        return notes
    files_by_disc: dict[int, list] = {}
    for f in iter_files(target):
        files_by_disc.setdefault(disc_for_track(f.metadata.get("discnumber")), []).append(f)
    if s["replace_embedded"]:
        album_types = set()
        for it in embeddable:
            if it.art_type != ArtType.DISC:
                album_types.update(PICARD_TYPES[it.art_type])
        if album_types:
            for o in [target] + list(getattr(target, "tracks", [])) + list(iter_files(target)):
                _strip_types(o, album_types)
        # disc art is replaced only on the discs that get new disc art
        for d in {it.disc_number or 1 for it in embeddable if it.art_type == ArtType.DISC}:
            for f in files_by_disc.get(d, []):
                _strip_types(f, {"medium"})
    for it in embeddable:
        c = it.candidate
        if c.data is None:
            notes.append(f"{it.art_type.value}: image data missing")
            continue
        data, w, h, _fmt = imaging.prepare(c.data, int(s["embed_max_side"] or 0), "original", int(s["jpeg_quality"]))
        comment = c.comment if c.generated else (f"CoverUp: {c.provider}" if s["record_source_in_comment"] else "")
        if it.art_type == ArtType.DISC:
            comment = (comment + f" disc {it.disc_number}").strip()
        img = _make_image(data, it.art_type, comment, c.url)
        if it.art_type == ArtType.DISC:
            targets = files_by_disc.get(it.disc_number or 1, [])
            for f in targets:
                CoverArtSetter(CoverArtSetterMode.APPEND, img, f).set_coverart()
            log.info("Embedded disc %s art (%dx%d) into %d file(s)", it.disc_number, w, h, len(targets))
        else:
            CoverArtSetter(CoverArtSetterMode.APPEND, img, target).set_coverart()
            log.info("Embedded %s (%dx%d, %s) into %s", it.art_type.value, w, h, c.provider, getattr(target, "id", "cluster"))
    return notes


def picard_embeds_images() -> tuple[bool, bool]:
    """(Picard embeds images into tags, Picard embeds only one front image)."""
    try:
        from picard.config import get_config

        st = get_config().setting
        return bool(st["save_images_to_tags"]), bool(st["embed_only_one_front_image"])
    except Exception:
        return True, False


def schedule_files(target, items: list[PlanItem], s: Settings) -> FolderPlan | None:
    """Queue file writes for this album; they happen after Picard saves its files (final paths), or now."""
    file_items = []
    for it in items:
        if it.candidate.data is None:
            continue
        file_items.append(FileItem(it.art_type, it.candidate.data, it.candidate, it.disc_number, it.page))
    if not file_items:
        return None
    batch = uuid.uuid4().hex[:10]
    plan = FolderPlan(file_items, s, batch)
    key = key_of(target)
    STATE.pending[key] = plan
    log.info("Scheduled %d file(s) for %s (%s)", len(file_items), key, s["write_files_when"])
    if s["write_files_when"] == "immediately":
        write_now(target, plan)
    return plan


def write_now(target, plan: FolderPlan) -> list[F.WriteResult]:
    results = []
    folders = []
    for f in iter_files(target):
        d = os.path.dirname(f.filename)
        results += plan.write_for_folder(d, disc_for_track(f.metadata.get("discnumber")), imaging.prepare)
        if d not in folders:
            folders.append(d)
    _remember_batch(key_of(target), plan, folders)
    return results


def _remember_batch(key: str, plan: FolderPlan, folders: list[str]) -> None:
    dirs = set()
    for r in plan.results:
        if r.path is not None:
            dirs.add(str(r.path.parent))
    dirs.update(folders)
    prev = STATE.last_batch.get(key)
    if prev and prev[0] == plan.batch:
        dirs.update(prev[1])
    STATE.last_batch[key] = (plan.batch, sorted(dirs))


def on_file_saved(api, file) -> None:
    """Picard post-save hook: write pending images next to the file's final location."""
    try:
        Album, Cluster, File, Track = _classes()
        parent = file.parent_item
        target = parent.album if isinstance(parent, Track) else parent
        if target is None:
            return
        key = key_of(target)
        plan = STATE.pending.get(key)
        if plan is None:
            return
        folder = os.path.dirname(file.filename)
        plan.write_for_folder(folder, disc_for_track(file.metadata.get("discnumber")), imaging.prepare)
        _remember_batch(key, plan, [folder])
    except Exception:
        log.exception("Writing artwork after save failed")


def undo_last(target) -> list[str]:
    """Undo the files written by the last CoverUp apply for this album (restoring backups)."""
    key = key_of(target)
    info = STATE.last_batch.get(key)
    album_dirs: list[str] = []
    for f in iter_files(target):
        d = os.path.dirname(f.filename)
        if d not in album_dirs:
            album_dirs.append(d)
    s = STATE.settings()
    own = list(album_dirs)  # folders that belong to this album only
    for d in album_dirs:
        sub = os.path.join(d, s["folder_name"])
        if os.path.isdir(sub):
            own.append(sub)
    if info:
        batch, dirs = info
        own += [d for d in dirs if d not in own]
    else:
        # after a restart: take the newest batch found in the album's own folders, never from a shared
        # artist folder (that could belong to another album)
        batch = next((b for d in own if (b := F.last_batch(d))), None)
    if not batch:
        return []
    shared = []
    for d in album_dirs:
        p = Path(d)
        shared += [str(p.parent), str(p.parent.parent)]
    messages: list[str] = []
    for d in own + [x for x in shared if x not in own]:
        messages += [f"{d}: {m}" for m in F.undo_batch(d, batch)]
    STATE.last_batch.pop(key, None)
    STATE.pending.pop(key, None)
    log.info("Undo for %s (batch %s): %s", key, batch, messages or "nothing to undo")
    return messages


def set_status_variables(target, status: str, front: Candidate | None) -> None:
    values = {
        "_coverup_status": status,
        "_coverup_source": front.provider if front else "",
        "_coverup_confidence": front.tier.value if front else "",
        "_coverup_generated": "1" if (front and front.generated) else "",
    }
    objs = [target] + list(getattr(target, "tracks", [])) + list(iter_files(target))
    for o in objs:
        md = getattr(o, "metadata", None)
        if md is None:
            continue
        for k, v in values.items():
            if v:
                md[k] = v
            elif k in md:
                del md[k]


def apply_plan(target, items: list[PlanItem], s: Settings, embed_on: bool, files_on: bool, status: str = "applied") -> list[str]:
    """Embed and/or schedule files for the chosen items. Returns notes for the user."""
    notes: list[str] = []
    if embed_on:
        wanted = s.embed_art_types()
        notes += embed(target, [it for it in items if it.art_type in wanted], s)
    if files_on:
        schedule_files(target, items, s)
    front = next((it.candidate for it in items if it.art_type == ArtType.FRONT), None)
    set_status_variables(target, status, front)
    try:
        target.update()
    except Exception:
        pass
    return notes


def register_options(api) -> None:
    for key, default in DEFAULTS.items():
        api.plugin_config.register_option(key, default)
    from .settings import migrate

    changed = migrate(api.plugin_config)
    if changed:
        log.info("Settings updated to the new defaults: %s", ", ".join(changed))


