pytestmark = pytest.mark.usefixtures("qapp")
Q = Query(artist="Nightfall", album="Silver Horizons", year=1984, genre="Synthpop")


def test_eleven_builtin_templates_load():
    t = load_templates()
    assert {"art", "fantasy", "nature", "planetary", "cyberpunk", "minimal", "vintage", "photographic", "geometric", "gothic", "retropop"} <= set(t)
    for tpl in t.values():
        assert tpl.procedural in STYLES and len(tpl.palette) >= 2 and "{album}" in tpl.prompt


def test_user_template_overrides_builtin(tmp_path):
    (tmp_path / "fantasy.toml").write_text('title = "Mine"\nprompt = "my {album}"\n', encoding="utf-8")
    (tmp_path / "broken.toml").write_text("not = [valid", encoding="utf-8")
    t = load_templates(tmp_path)
    assert t["fantasy"].title == "Mine" and "broken" not in t


def test_prompt_placeholders_era_and_genre():
    p = build_prompt(load_templates()["planetary"], Q)
    assert '"Silver Horizons" by Nightfall' in p and "1980s" in p and "Synthpop" in p
    assert "1980s" not in build_prompt(load_templates()["planetary"], Q, match_era=False)
    assert era_cue(None) == "" and "1970s" in era_cue(1977)


def test_every_procedural_style_renders_deterministically():
    for style in STYLES:
        a = procedural(style, 256, 7, ["#102030", "#e0a040", "#40a0e0"])
        b = procedural(style, 256, 7, ["#102030", "#e0a040", "#40a0e0"])
        assert a.width() == 256 and a == b, style
        fp = imaging.fingerprint(imaging.encode(a, "png"))
        assert fp is not None and not fp.blank, style


def test_compose_draws_text_and_logo():
    bg = procedural("gradient", 512, 1, ["#000000", "#333333"])
    plain = imaging.fingerprint(imaging.encode(compose(bg, show_logo=False, show_title=False), "png"))
    texted = imaging.fingerprint(imaging.encode(compose(bg, "Nightfall", "Silver Horizons", 1984), "png"))
    assert hamming(plain.phash, texted.phash) > 0
    logo = imaging.load(make_image("b", w=400, h=150, fmt="png"))
    with_logo = compose(bg, "Nightfall", "Silver Horizons", logo=logo)
    assert with_logo.width() == 512
    assert disc_mask(with_logo).hasAlphaChannel()


def S(**kw):
    return Settings.from_mapping(kw)


def test_template_generation_produces_labelled_candidates():
    t = load_templates()["fantasy"]
    out = generate(S(ai_size=256), FakeHttp(), Q, CreativeOptions("template", t, count=3, logo_data=make_image("b", w=300, h=100)))
    assert len(out) == 3
    for c in out:
        assert c.generated and c.tier == Tier.G and c.art_type == ArtType.FRONT
        assert c.comment.startswith("Generated by CoverUp") and c.extra["template"] == "fantasy" and c.extra["logo"]
        assert imaging.size_of(c.data) == (256, 256)
    assert len({c.extra["seed"] for c in out}) == 3


def png_b64():
    return base64.b64encode(make_image("c", 256, fmt="png")).decode()


def test_automatic1111_backend_and_img2img():
    http = FakeHttp({"http://127.0.0.1:7860/sdapi/v1/txt2img": {"images": [png_b64(), png_b64()]},
                     "http://127.0.0.1:7860/sdapi/v1/img2img": {"images": [png_b64()]}})
    s = S(ai_backend="automatic1111", ai_url="http://127.0.0.1:7860", ai_size=256)
    t = load_templates()["nature"]
    out = generate(s, http, Q, CreativeOptions("ai", t, count=2, seed=5))
    assert len(out) == 2 and out[0].extra["method"] == "ai" and out[0].extra["seed"] == 5
    url, body = http.posts[0]
    assert url.endswith("/txt2img") and body["seed"] == 5 and "Silver Horizons" in body["prompt"] and "text" in body["negative_prompt"]
    generate(s, http, Q, CreativeOptions("ai", t, count=1, reference=make_image("a", 300)))
    assert http.posts[-1][0].endswith("/img2img") and http.posts[-1][1]["init_images"]


def test_openai_compatible_backend_shapes():
    http = FakeHttp({"http://localhost:8000/v1/images/generations": {"data": [{"b64_json": png_b64()}]}})
    s = S(ai_backend="openai", ai_url="http://localhost:8000", ai_size=256, ai_model="m1")
    out = generate(s, http, Q, CreativeOptions("ai", load_templates()["art"], count=1))
    assert len(out) == 1 and http.posts[0][1]["model"] == "m1" and http.posts[0][1]["size"] == "256x256"


def test_remote_ai_needs_consent_and_never_gets_reference_without_permission():
    http = FakeHttp({"https://api.example.com/v1/images/generations": {"data": [{"b64_json": png_b64()}]}})
    s = S(ai_backend="openai", ai_url="https://api.example.com", ai_size=256)
    with pytest.raises(ConsentRequired) as exc:
        generate(s, http, Q, CreativeOptions("ai", load_templates()["art"], count=1))
    assert exc.value.host == "api.example.com" and http.posts == []
    s2 = S(ai_backend="custom", ai_url="https://api.example.com/v1/images/generations", ai_size=256, ai_consented_hosts=["api.example.com"])
    generate(s2, http, Q, CreativeOptions("ai", load_templates()["art"], count=1, reference=make_image("a", 300)))
    assert "init_image" not in http.posts[-1][1]  # remote reference images need a separate opt-in


def test_ai_failure_falls_back_to_offline_template():
    http = FakeHttp({"http://127.0.0.1:7860/sdapi/v1/txt2img": {"images": []}})
    s = S(ai_backend="automatic1111", ai_url="http://127.0.0.1:7860", ai_size=256)
    out = generate(s, http, Q, CreativeOptions("ai", load_templates()["art"], count=1))
    assert out and out[0].extra["method"] == "template"


def test_is_remote():
    assert not ai.is_remote("http://127.0.0.1:7860") and not ai.is_remote("http://192.168.1.20:7860")
    assert not ai.is_remote("http://localhost:8188") and ai.is_remote("https://api.openai.com/v1")


def test_resolve_custom_template():
    t = resolve_template(S(creative_template=CUSTOM, creative_custom_prompt="x {album}"))
    assert t.name == CUSTOM and build_prompt(t, Q) == "x Silver Horizons"
